      return `${base}ההסבר צריך להציג תהליך עבודה שלם: זיהוי מצב מסוכן, איסוף נתונים מהשטח, הערכת חומרה והסתברות, בחירת בקרה מתאימה, הטמעה מול מנהלים ועובדים, ותיעוד המעקב. תשובה טובה תסביר גם מה עלול להשתבש אם המנגנון נשאר פורמלי בלבד: נהלים שאינם מוכרים, ליקויים שאינם נסגרים, או הדרכה שאינה משנה התנהגות. תפקיד ממונה הבטיחות הוא להפוך את הנושא לשגרת ניהול ולא לאירוע חד פעמי.`;
