  const HARD_SWAP = new Set(["safety-officer-regulations", "safety-management", "machine-guarding", "electrical-safety", "fire-safety"]);

  function makeQuestion(topic, pattern, index) {
    const id = `open-${topic.code}-${String(index + 1).padStart(3, "0")}`;
    const difficulty = HARD_SWAP.has(topic.code) && (index === 4 || index === 12) ? "קשה" : pattern.difficulty;
    const questionStyle = getQuestionStyle(topic, pattern, index);
    const examCritical = ["legal-responsibility", "safety-officer", "inspection-law", "safety-officer-regulations", "machine-guarding", "electrical-safety", "fire-safety", "lifting-equipment", "steam-boilers"].includes(topic.code);
    const question = buildQuestionText(topic, pattern, questionStyle, index);
    const modelAnswerShort = buildShortAnswer(topic, pattern, questionStyle);
    const modelAnswerFull = buildFullAnswer(topic, pattern, questionStyle);
    return {
      id,
      type: "open",
      lessonIds: [topic.lesson],
      topicIds: [topic.code],
      mainTopic: topic.mainTopic,
      subTopic: topic.subTopic,
      difficulty,
      question,
      expectedAnswer: modelAnswerFull,
      modelAnswerShort,
      modelAnswerFull,
      rubric: buildRubric(topic, pattern),
      commonMistakes: buildCommonMistakes(topic, questionStyle),
      weakTopicTags: topic.weakTopicTags,
      examCritical,
      reviewRequired: topic.reviewRequired,
      questionStyle,
      questionKind: pattern.label,
      scenarioBased: pattern.scenarioBased,
      comparisonQuestion: pattern.comparison,
      applicationQuestion: pattern.application
    };
  }

  function getQuestionStyle(topic, pattern, index) {
    if (index === 1 && ["legal-responsibility", "inspection-law", "safety-officer-regulations", "steam-boilers", "lifting-equipment"].includes(topic.code)) return "legalResponsibility";
    if (index === 11 && ["safety-management", "machine-guarding", "electrical-safety", "fire-safety", "safety-officer"].includes(topic.code)) return "correctiveActions";
    return pattern.questionStyle;
  }

